<h1>Privacy policy</h1>
<p class="muted">Last updated: September 12, 2026</p>
<p>
	This policy explains how 4D chess at 4dchess.lol, maintained by 0xmiki ("we"), handles information
	when you visit or play.
</p>

<h2>Information we handle</h2>
<ul>
	<li>
		<strong>Guest sessions:</strong> online play creates a guest identity and session records. We store
		a generated identifier and display name; you do not need to supply a real name or email address.
	</li>
	<li>
		<strong>Online games:</strong> we store players' identifiers, moves, results, time controls, invitations,
		matchmaking requests, and connection status to run games and allow reconnection.
	</li>
	<li>
		<strong>Chat:</strong> we store messages you send, their sender, room, and expiry time. Do not share
		sensitive personal information in chat.
	</li>
	<li>
		<strong>Technical information:</strong> our hosting and backend services process connection and request
		information, such as IP addresses and browser details. Guest signup uses your IP address for rate
		limiting and derives a pseudonymous key for backend abuse prevention. Error logs help us diagnose
		failures.
	</li>
	<li>
		<strong>Messages to us:</strong> if you contact us, we receive the information you choose to send.
	</li>
</ul>

<h2>Why we use it</h2>
<p>
	We use this information to provide games, authenticate guests, match opponents, deliver chat,
	restore sessions, prevent abuse, fix errors, and produce aggregate game statistics. Where data
	protection law requires a legal basis, providing the service relies on performing our agreement
	with you; security, diagnostics, and service statistics rely on our legitimate interests in
	running a reliable service. We may also process information to meet legal obligations.
</p>

<h2>Cookies and browser storage</h2>
<p>
	Session cookies keep your guest session authenticated. Guest sessions are configured to expire
	after 30 days and may renew with use. Local and session storage remember active matches,
	matchmaking requests, computer games, and sound and motion preferences. Computer games run in your
	browser. You can clear site data in your browser settings, but doing so may lose saved games and
	access to your guest identity. Clearing browser data does not delete server records.
</p>

<h2>Optional computer-game statistics</h2>
<p>
	If you choose Accept in our privacy panel, a human move in a computer game can send a random
	per-game reporting token and consent version to Convex. We use these to count reported games and
	prevent duplicate reports; we do not send your moves, board, display name, or account identifier
	with the report. These requests still involve the technical connection information described
	above. Computer play works without reporting. This optional processing relies on your consent.
</p>
<p>
	Essential only disables optional reporting. Privacy settings in the footer lets you change your
	choice at any time. We remember acceptance and refusal in this browser for 180 days, together with
	the choice date and consent version. Another browser or clearing site data means choosing again. A
	reporting token and acknowledgement are saved with the game after consent, so resuming does not
	count it again. Withdrawing consent stops future reports; already published aggregate counts
	remain.
</p>
<p>
	Reporting tokens become eligible for deletion after two days and are removed by daily cleanup,
	which may be delayed. Daily aggregate counts have no automatic deletion period. We do not publish
	reporting tokens or use them to identify players across games.
</p>

<h2>Who can see information</h2>
<p>
	People with a room link can watch the game, including player display names, moves, and results.
	Room chat is available to the room's players. Public statistics show aggregate activity.
	Cloudflare hosts the website and Convex provides the backend, database, and authentication
	infrastructure. These providers process information needed to operate the service and may process
	it outside your country. Information may also be disclosed when required by law or necessary to
	protect the service and its users.
</p>
<p>
	The site does not include advertising trackers or sell personal information. Links to GitHub,
	Discord, and X take you to separate services with their own privacy policies.
</p>

<h2>How long information stays</h2>
<p>
	Chat messages expire 24 hours after sending and are removed by scheduled cleanup. Cancelled or
	expired games that never started become eligible for deletion after seven days. Cleanup may take
	longer if jobs are delayed. Played games, including completed games, guest accounts, and
	participant records currently have no automatic deletion period; they remain for game history and
	continuity. Temporary presence and rate-limit records expire separately. Provider logs and backups
	follow the providers' retention settings and may outlast deletion from the live service.
</p>

<h2>Your choices and rights</h2>
<p>
	Depending on your location, you may have rights to access, correct, delete, or receive a copy of
	your personal information, restrict its use, or object to processing. You may also complain to
	your local data protection authority. Contact the maintainer to make a request. We may need
	information to verify that a guest identity belongs to you; never send session cookies or tokens.
</p>

<h2>Children</h2>
<p>
	The service is not intended for children under 13. If you believe a child under 13 has provided
	personal information, contact us so we can investigate and address it.
</p>

<h2>Contact and changes</h2>
<p>
	Contact the maintainer at <a href="mailto:support@4dchess.lol">support@4dchess.lol</a>. Ask for a
	private channel before sharing personal information. We will update this page when our practices
